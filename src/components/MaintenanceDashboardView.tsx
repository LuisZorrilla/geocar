import { useMemo, useState } from 'react';
import { useMoney } from '../lib/money.tsx';
import {
  AlertTriangle,
  CalendarClock,
  DollarSign,
  MapPin,
  Wrench,
} from 'lucide-react';
import type {
  MaintenanceDashboardMetrics,
  Vehicle,
  WorkOrder,
} from '../shared/types.ts';
import {
  ASSET_TYPE_LABELS,
  formatServiceDate,
  getServiceDateDeltaDays,
  MAINTENANCE_META,
  sortWorkOrdersByPriority,
  WORK_ORDER_PRIORITY_META,
  WORK_ORDER_STATUS_META,
} from '../lib/api.ts';
import { Pagination, usePagination } from './Pagination.tsx';

interface MaintenanceDashboardViewProps {
  tenantId: string;
  vehicles: Vehicle[];
  workOrders: WorkOrder[];
  metrics?: MaintenanceDashboardMetrics;
  onOpenDossier: (vehicleId: string) => void;
  onGoToOrders: (workOrderId?: string) => void;
  onGoToPending: () => void;
}

export function MaintenanceDashboardView({
  tenantId,
  vehicles,
  workOrders,
  metrics,
  onOpenDossier,
  onGoToOrders,
  onGoToPending,
}: MaintenanceDashboardViewProps) {
  const monthlyCosts = metrics?.monthlyCosts ?? [];
  const corridorMetrics = metrics?.corridorMetrics ?? [];
  const money = useMoney();
  // The metrics come in one currency: the company's, or the platform reference one in the consolidated view.
  const cur = metrics?.currency ?? money.currencyOf()?.code ?? null;
  const fm = (n: number, opts?: { compact?: boolean }) => money.fmtIn(n, cur, opts);
  const curCode = cur ?? 'sin moneda';
  /** Short axis label in the metrics currency: "US$1k", "$250k", "CLP$80". */
  const axisTick = (v: number) => {
    const sym = money.find(cur)?.symbol ?? '';
    return v >= 1000 ? `${sym}${Math.round(v / 1000).toLocaleString('es-AR')}k` : `${sym}${Math.round(v)}`;
  };

  const [selectedMonthKey, setSelectedMonthKey] = useState<string | null>(null);
  const activeMonth =
    monthlyCosts.find((m) => m.monthKey === selectedMonthKey) ??
    monthlyCosts[monthlyCosts.length - 1] ??
    null;

  const overdueAndFaultAlerts = useMemo(() => {
    const rank = (v: Vehicle) => {
      if (v.maintenanceStatus === 'vencido') return 0;
      if (v.faultCodes.some((f) => f.severity === 'critica')) return 1;
      if (v.maintenanceStatus === 'proximo') return 2;
      return 3;
    };
    return [...vehicles]
      .filter((v) => v.maintenanceStatus !== 'al_dia' || v.faultCodes.length > 0)
      .sort((a, b) => rank(a) - rank(b));
  }, [vehicles]);

  const upcomingOrders = useMemo(() => {
    const active = workOrders.filter(
      (w) =>
        w.status === 'abierta' ||
        w.status === 'en_taller' ||
        w.status === 'esperando_refacciones'
    );
    return sortWorkOrdersByPriority(active, vehicles);
  }, [workOrders, vehicles]);

  const corridorPagination = usePagination(corridorMetrics, `${tenantId}|postgis|${corridorMetrics.length}`, 5);
  const alertsPagination = usePagination(overdueAndFaultAlerts, `${tenantId}|m-alerts|${overdueAndFaultAlerts.length}`, 5);
  const ordersPagination = usePagination(upcomingOrders, `${tenantId}|m-upcoming|${upcomingOrders.length}`, 5);

  const maxMonthlyTotal = Math.max(
    1,
    ...monthlyCosts.map((m) => m.total)
  );

  const sixMonthTotals = useMemo(() => {
    return monthlyCosts.reduce(
      (acc, m) => ({
        refacciones: acc.refacciones + m.refacciones,
        insumos: acc.insumos + m.insumos,
        manoObra: acc.manoObra + m.manoObra,
        total: acc.total + m.total,
        orders: acc.orders + m.ordersCount,
      }),
      { refacciones: 0, insumos: 0, manoObra: 0, total: 0, orders: 0 }
    );
  }, [monthlyCosts]);

  const upcomingCount = metrics?.upcomingOrdersCount ?? upcomingOrders.length;
  const autoGeneratedCount =
    metrics?.autoGeneratedOrdersCount ?? upcomingOrders.filter((w) => w.autoGenerated).length;
  const lowStockCount = metrics?.lowStockPartsCount ?? 0;
  const overdueCount =
    metrics?.overdueUnitsCount ??
    vehicles.filter((v) => v.maintenanceStatus === 'vencido').length;
  const faultUnitsCount =
    metrics?.criticalFaultUnitsCount ??
    vehicles.filter((v) => v.faultCodes.length > 0).length;
  const currentMonthTotal = metrics?.currentMonthTotal ?? (monthlyCosts[monthlyCosts.length - 1]?.total ?? 0);
  const insideCorridor = metrics?.unitsInsideCorridor ?? vehicles.length;
  const outsideCorridor = metrics?.unitsOutsideCorridor ?? 0;
  const avgDistKm = metrics?.avgDistanceToHubKm ?? 0;

  return (
    <div className="space-y-4">
      {/* Top 4 Summary Cards */}
      <div className="grid grid-cols-1 sm:grid-cols-2 xl:grid-cols-4 gap-3">
        <div className="bg-[#11192C] border border-slate-800/80 rounded-xl p-4 flex flex-col justify-between">
          <div className="flex items-center justify-between text-xs text-slate-400">
            <span>Próximas órdenes de trabajo</span>
            <CalendarClock className="w-4 h-4 text-sky-400 shrink-0" />
          </div>
          <div className="mt-2 flex items-baseline justify-between gap-2">
            <div className="text-2xl font-semibold font-mono tabular-nums text-sky-400">
              {upcomingCount}
            </div>
            <span className="text-xs font-mono tabular-nums text-slate-400">
              {autoGeneratedCount} auto · {workOrders.length} totales
            </span>
          </div>
          <div className="mt-2 text-[11px] text-slate-400 truncate">
            {upcomingOrders[0]
              ? `Prioridad #1: ${upcomingOrders[0].unitCode} · ${WORK_ORDER_PRIORITY_META[upcomingOrders[0].priority].label}`
              : 'Sin órdenes pendientes en cola'}
          </div>
        </div>

        <div className="bg-[#11192C] border border-slate-800/80 rounded-xl p-4 flex flex-col justify-between">
          <div className="flex items-center justify-between text-xs text-slate-400">
            <span>Alertas de servicios vencidos</span>
            <AlertTriangle className="w-4 h-4 text-rose-400 shrink-0" />
          </div>
          <div className="mt-2 flex items-baseline justify-between gap-2">
            <div className="text-2xl font-semibold font-mono tabular-nums text-rose-400">
              {overdueCount}
            </div>
            <span className="text-xs font-mono tabular-nums text-amber-400">
              {faultUnitsCount} con DTC activo
            </span>
          </div>
          <div className="mt-2 text-[11px] text-slate-400 flex items-center justify-between">
            <span>Por horómetro / km / fecha</span>
            <button
              type="button"
              onClick={onGoToPending}
              className="text-sky-400 hover:text-sky-300 font-medium cursor-pointer whitespace-nowrap"
            >
              Ver alertas →
            </button>
          </div>
        </div>

        <div className="bg-[#11192C] border border-slate-800/80 rounded-xl p-4 flex flex-col justify-between">
          <div className="flex items-center justify-between text-xs text-slate-400">
            <span>Costo mensual refacciones / taller</span>
            <DollarSign className="w-4 h-4 text-emerald-400 shrink-0" />
          </div>
          <div className="mt-2 flex items-baseline justify-between gap-2">
            <div className="text-2xl font-semibold font-mono tabular-nums text-emerald-400">
              {fm(currentMonthTotal)}
            </div>
            <span className={`text-xs font-mono ${lowStockCount > 0 ? 'text-rose-400' : 'text-slate-400'}`}>
              {lowStockCount > 0 ? `${lowStockCount} SKU bajo mín.` : 'Stock óptimo'}
            </span>
          </div>
          <div className="mt-2 text-[11px] font-mono tabular-nums text-slate-400 truncate">
            Acumulado 6m: {fm(sixMonthTotals.total)} {curCode} ({sixMonthTotals.orders} OT)
          </div>
          {metrics?.consolidated && (
            <div className="mt-1 text-[10px] text-slate-500" title="Cada orden se convierte con el tipo de cambio de su fecha">
              Consolidado en {curCode} con el TC de la fecha de cada orden
              {metrics.excludedOrders ? ` · ${metrics.excludedOrders} OT sin TC fuera de la suma` : ''}
            </div>
          )}
        </div>

        <div className="bg-[#11192C] border border-slate-800/80 rounded-xl p-4 flex flex-col justify-between">
          <div className="flex items-center justify-between text-xs text-slate-400">
            <span>Seguimiento PostGIS (ST_DWithin 25 km)</span>
            <MapPin className="w-4 h-4 text-amber-400 shrink-0" />
          </div>
          <div className="mt-2 flex items-baseline justify-between gap-2">
            <div className="text-2xl font-semibold font-mono tabular-nums text-slate-100">
              {insideCorridor}
              <span className="text-sm font-normal text-slate-400"> / {insideCorridor + outsideCorridor}</span>
            </div>
            <span className="text-xs font-mono tabular-nums text-amber-300">
              {outsideCorridor} fuera geocerca
            </span>
          </div>
          <div className="mt-2 text-[11px] font-mono tabular-nums text-slate-400 truncate">
            Dist. prom. hub: {avgDistKm.toLocaleString('es-MX')} km · {(metrics?.totalFleetEngineHours ?? 0).toLocaleString('es-MX')} h
          </div>
        </div>
      </div>

      {/* Monthly Cost Breakdown Chart + Selected Month Inspector */}
      <div className="grid grid-cols-1 xl:grid-cols-12 gap-4">
        <div className="xl:col-span-8 bg-[#11192C] border border-slate-800/80 rounded-xl p-4 space-y-3">
          <div className="flex flex-wrap items-center justify-between gap-2 border-b border-slate-800/80 pb-3">
            <div>
              <h3 className="text-sm font-semibold text-slate-100">
                Costos mensuales de mantenimiento (últimos 6 meses)
              </h3>
              <p className="text-xs text-slate-400">
                Desglose acumulado en refacciones, insumos y mano de obra ({curCode}) · Haz clic en un mes para inspeccionar
              </p>
            </div>
            <div className="flex flex-wrap items-center gap-3 text-xs">
              <span className="inline-flex items-center gap-1.5 text-slate-300">
                <span className="w-2.5 h-2.5 rounded-xs bg-sky-500 inline-block" />
                Refacciones
              </span>
              <span className="inline-flex items-center gap-1.5 text-slate-300">
                <span className="w-2.5 h-2.5 rounded-xs bg-emerald-500 inline-block" />
                Insumos
              </span>
              <span className="inline-flex items-center gap-1.5 text-slate-300">
                <span className="w-2.5 h-2.5 rounded-xs bg-amber-500 inline-block" />
                Mano de obra
              </span>
            </div>
          </div>

          {monthlyCosts.length === 0 ? (
            <div className="py-12 text-center text-xs text-slate-400">
              Sin historial mensual calculado para el ámbito seleccionado.
            </div>
          ) : (
            <div className="w-full overflow-x-auto">
              <svg
                viewBox="0 0 660 230"
                className="w-full min-w-[460px] h-56 select-none"
                role="img"
                aria-label="Gráfica mensual de costos de refacciones, insumos y mano de obra"
              >
                {/* Horizontal Grid Lines */}
                {[0, 0.25, 0.5, 0.75, 1].map((ratio) => {
                  const y = 185 - ratio * 150;
                  const val = axisTick(maxMonthlyTotal * ratio);
                  return (
                    <g key={ratio}>
                      <line
                        x1={56}
                        y1={y}
                        x2={644}
                        y2={y}
                        stroke="#1E293B"
                        strokeDasharray={ratio === 0 ? undefined : '3 3'}
                        strokeWidth={1}
                      />
                      <text
                        x={48}
                        y={y + 4}
                        textAnchor="end"
                        fill="#64748B"
                        fontSize={10}
                        fontFamily="ui-monospace, monospace"
                      >
                        {val}
                      </text>
                    </g>
                  );
                })}

                {/* Stacked Bars */}
                {monthlyCosts.map((m, idx) => {
                  const slotWidth = (644 - 68) / Math.max(1, monthlyCosts.length);
                  const barWidth = Math.min(54, slotWidth * 0.54);
                  const x = 68 + idx * slotWidth + (slotWidth - barWidth) / 2;

                  const hRef = (m.refacciones / maxMonthlyTotal) * 150;
                  const hIns = (m.insumos / maxMonthlyTotal) * 150;
                  const hLab = (m.manoObra / maxMonthlyTotal) * 150;

                  const yRef = 185 - hRef;
                  const yIns = yRef - hIns;
                  const yLab = yIns - hLab;

                  const isActive = activeMonth?.monthKey === m.monthKey;

                  return (
                    <g
                      key={m.monthKey}
                      onClick={() => setSelectedMonthKey(m.monthKey)}
                      onMouseEnter={() => setSelectedMonthKey(m.monthKey)}
                      className="cursor-pointer"
                    >
                      {isActive && (
                        <rect
                          x={x - 6}
                          y={26}
                          width={barWidth + 12}
                          height={165}
                          rx={6}
                          fill="#1E293B"
                          fillOpacity={0.45}
                        />
                      )}
                      {hRef > 0 && (
                        <rect
                          x={x}
                          y={yRef}
                          width={barWidth}
                          height={hRef}
                          fill="#0EA5E9"
                          opacity={isActive ? 1 : 0.85}
                        />
                      )}
                      {hIns > 0 && (
                        <rect
                          x={x}
                          y={yIns}
                          width={barWidth}
                          height={hIns}
                          fill="#10B981"
                          opacity={isActive ? 1 : 0.85}
                        />
                      )}
                      {hLab > 0 && (
                        <rect
                          x={x}
                          y={yLab}
                          width={barWidth}
                          height={hLab}
                          fill="#F59E0B"
                          opacity={isActive ? 1 : 0.85}
                        />
                      )}
                      <text
                        x={x + barWidth / 2}
                        y={Math.max(18, yLab - 6)}
                        textAnchor="middle"
                        fill={isActive ? '#F8FAFC' : '#94A3B8'}
                        fontSize={10}
                        fontWeight={isActive ? 700 : 500}
                        fontFamily="ui-monospace, monospace"
                      >
                        {fm(m.total, { compact: true })}
                      </text>
                      <text
                        x={x + barWidth / 2}
                        y={205}
                        textAnchor="middle"
                        fill={isActive ? '#38BDF8' : '#CBD5E1'}
                        fontSize={11}
                        fontWeight={isActive ? 700 : 500}
                      >
                        {m.monthLabel}
                      </text>
                      <text
                        x={x + barWidth / 2}
                        y={219}
                        textAnchor="middle"
                        fill="#64748B"
                        fontSize={9}
                        fontFamily="ui-monospace, monospace"
                      >
                        {m.ordersCount} OT
                      </text>
                    </g>
                  );
                })}
              </svg>
            </div>
          )}
        </div>

        {/* Selected Month Cost Inspector */}
        <div className="xl:col-span-4 bg-[#11192C] border border-slate-800/80 rounded-xl p-4 flex flex-col justify-between space-y-3 text-xs">
          {activeMonth ? (
            <>
              <div className="space-y-3">
                <div className="flex items-center justify-between border-b border-slate-800 pb-2.5">
                  <div>
                    <div className="text-slate-400">Detalle del periodo</div>
                    <div className="text-base font-semibold text-slate-100 capitalize">
                      {activeMonth.monthLabel} ({activeMonth.monthKey})
                    </div>
                  </div>
                  <span className="font-mono tabular-nums text-sky-300 font-semibold">
                    {activeMonth.ordersCount} órdenes
                  </span>
                </div>

                <div className="p-3 rounded-lg bg-[#0B1120] border border-slate-800 flex items-center justify-between">
                  <span className="text-slate-400">Total ejercido en el mes</span>
                  <span className="text-lg font-semibold font-mono tabular-nums text-emerald-400">
                    {fm(activeMonth.total)} {curCode}
                  </span>
                </div>

                <div className="space-y-2">
                  {[
                    {
                      label: 'Refacciones',
                      value: activeMonth.refacciones,
                      barClass: 'bg-sky-500',
                      textClass: 'text-sky-300',
                    },
                    {
                      label: 'Insumos (aceites/lubricantes)',
                      value: activeMonth.insumos,
                      barClass: 'bg-emerald-500',
                      textClass: 'text-emerald-300',
                    },
                    {
                      label: 'Mano de obra y taller',
                      value: activeMonth.manoObra,
                      barClass: 'bg-amber-500',
                      textClass: 'text-amber-300',
                    },
                  ].map((item) => {
                    const pct =
                      activeMonth.total > 0
                        ? Math.round((item.value / activeMonth.total) * 100)
                        : 0;
                    return (
                      <div key={item.label} className="p-2.5 rounded-lg bg-[#0B1120] border border-slate-800/80 space-y-1.5">
                        <div className="flex items-center justify-between">
                          <span className="text-slate-300">{item.label}</span>
                          <span className={`font-mono tabular-nums font-semibold ${item.textClass}`}>
                            {fm(item.value)} ({pct}%)
                          </span>
                        </div>
                        <div className="h-1.5 w-full rounded-full bg-slate-800 overflow-hidden">
                          <div className={`h-full ${item.barClass}`} style={{ width: `${pct}%` }} />
                        </div>
                      </div>
                    );
                  })}
                </div>
              </div>

              <div className="pt-2 border-t border-slate-800 flex items-center justify-between text-[11px] text-slate-400 font-mono tabular-nums">
                <span>Refacciones 6m: {fm(sixMonthTotals.refacciones)}</span>
                <span>Insumos 6m: {fm(sixMonthTotals.insumos)}</span>
              </div>
            </>
          ) : (
            <div className="py-10 text-center text-slate-400">
              Selecciona un mes para ver el desglose financiero.
            </div>
          )}
        </div>
      </div>

      {/* PostgreSQL / PostGIS Spatial Fleet Tracking Table (5 per page) */}
      <div className="bg-[#11192C] border border-slate-800/80 rounded-xl overflow-hidden">
        <div className="px-4 py-3 border-b border-slate-800/80 flex flex-wrap items-center justify-between gap-2">
          <div>
            <h3 className="text-sm font-semibold text-slate-100">
              Métricas espaciales PostgreSQL / PostGIS por corredor de flota
            </h3>
            <p className="text-xs text-slate-400 font-mono">
              {metrics?.engine ?? 'PostgreSQL 16 + PostGIS 3.4 · ST_DWithin(25 km)'} ·{' '}
              {(metrics?.totalFleetOdometerKm ?? 0).toLocaleString('es-MX')} km totales recorridos
            </p>
          </div>
          <span className="text-xs font-mono tabular-nums text-sky-300">
            {corridorMetrics.length} corredores geoespaciales activos
          </span>
        </div>
        <div className="overflow-x-auto">
          <table className="w-full text-left border-collapse">
            <thead>
              <tr className="border-b border-slate-800 text-xs font-medium text-slate-400 bg-[#0F172A]">
                <th className="py-2.5 px-4">Geocerca / Corredor</th>
                <th className="py-2.5 px-4">Base / Sucursal</th>
                <th className="py-2.5 px-4 text-right">Cobertura ST_DWithin</th>
                <th className="py-2.5 px-4 text-right">Dist. prom. hub</th>
                <th className="py-2.5 px-4 text-right">Horómetro prom.</th>
                <th className="py-2.5 px-4 text-right">Odómetro acumulado</th>
                <th className="py-2.5 px-4 text-right">Vencidos / DTC</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-800/60 text-xs">
              {corridorPagination.pagedItems.length === 0 ? (
                <tr>
                  <td colSpan={7} className="py-6 px-4 text-center text-slate-400">
                    Sin corredores espaciales registrados.
                  </td>
                </tr>
              ) : (
                corridorPagination.pagedItems.map((cm) => (
                  <tr key={`${cm.geofenceName}-${cm.branch}`} className="hover:bg-slate-800/30">
                    <td className="py-2.5 px-4 font-medium text-slate-100">{cm.geofenceName}</td>
                    <td className="py-2.5 px-4 text-slate-300">{cm.branch}</td>
                    <td className="py-2.5 px-4 text-right font-mono tabular-nums">
                      <span className="text-emerald-400">{cm.insideCorridorCount} dentro</span>
                      {cm.outsideCorridorCount > 0 && (
                        <span className="text-amber-400"> · {cm.outsideCorridorCount} fuera</span>
                      )}
                    </td>
                    <td className="py-2.5 px-4 text-right font-mono tabular-nums text-sky-300">
                      {cm.avgDistanceToHubKm.toLocaleString('es-MX')} km
                    </td>
                    <td className="py-2.5 px-4 text-right font-mono tabular-nums text-slate-200">
                      {cm.avgEngineHours.toLocaleString('es-MX')} h
                    </td>
                    <td className="py-2.5 px-4 text-right font-mono tabular-nums text-slate-300">
                      {cm.totalOdometerKm.toLocaleString('es-MX')} km
                    </td>
                    <td className="py-2.5 px-4 text-right font-mono tabular-nums">
                      <span className={cm.overdueCount > 0 ? 'text-rose-400 font-semibold' : 'text-slate-400'}>
                        {cm.overdueCount} venc.
                      </span>
                      {' · '}
                      <span className={cm.faultUnitsCount > 0 ? 'text-amber-400' : 'text-slate-500'}>
                        {cm.faultUnitsCount} DTC
                      </span>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
        <Pagination
          page={corridorPagination.page}
          totalItems={corridorPagination.totalItems}
          pageSize={5}
          onPageChange={corridorPagination.setPage}
        />
      </div>

      {/* Bottom 2-Column Operational Lists (5 items per page each) */}
      <div className="grid grid-cols-1 xl:grid-cols-2 gap-4">
        {/* Overdue Services & DTC Alerts */}
        <div className="bg-[#11192C] border border-slate-800/80 rounded-xl overflow-hidden flex flex-col justify-between">
          <div>
            <div className="px-4 py-3 border-b border-slate-800/80 flex items-center justify-between gap-2">
              <div className="text-sm font-semibold text-slate-100">
                Alertas de servicios vencidos y fallas DTC ({overdueAndFaultAlerts.length})
              </div>
              <button
                type="button"
                onClick={onGoToPending}
                className="text-xs text-sky-400 hover:text-sky-300 cursor-pointer whitespace-nowrap"
              >
                Ver tabla completa
              </button>
            </div>
            <div className="divide-y divide-slate-800/60 text-xs">
              {alertsPagination.pagedItems.length === 0 ? (
                <div className="py-6 px-4 text-center text-slate-400">
                  Toda la flota está al día y sin fallas activas.
                </div>
              ) : (
                alertsPagination.pagedItems.map((v) => {
                  const maint = MAINTENANCE_META[v.maintenanceStatus];
                  const deltaDays = getServiceDateDeltaDays(v.nextServiceDate);
                  return (
                    <div key={v.id} className="px-4 py-3 flex items-center justify-between gap-3 hover:bg-slate-800/25">
                      <div className="min-w-0">
                        <div className="flex items-center gap-2">
                          <span className="font-semibold text-slate-100">{v.unitCode}</span>
                          <span className="text-slate-400 truncate">
                            {ASSET_TYPE_LABELS[v.assetType]} · {v.branch}
                          </span>
                        </div>
                        <div className="text-slate-400 font-mono tabular-nums mt-0.5">
                          <span className={maint.colorClass}>{maint.label}</span>
                          {' · '}
                          {v.engineHours} h / {v.nextServiceHours} h · {formatServiceDate(v.nextServiceDate)}
                          {deltaDays < 0 ? ` (${Math.abs(deltaDays)}d atraso)` : ''}
                        </div>
                        {v.faultCodes.length > 0 && (
                          <div className="text-amber-300 font-mono mt-0.5 truncate">
                            {v.faultCodes[0].code} · {v.faultCodes[0].description}
                          </div>
                        )}
                      </div>
                      <button
                        type="button"
                        onClick={() => onOpenDossier(v.id)}
                        className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 cursor-pointer whitespace-nowrap shrink-0"
                      >
                        <Wrench className="w-3.5 h-3.5 text-sky-400" />
                        Abrir ficha
                      </button>
                    </div>
                  );
                })
              )}
            </div>
          </div>
          <Pagination
            page={alertsPagination.page}
            totalItems={alertsPagination.totalItems}
            pageSize={5}
            onPageChange={alertsPagination.setPage}
          />
        </div>

        {/* Upcoming Work Orders */}
        <div className="bg-[#11192C] border border-slate-800/80 rounded-xl overflow-hidden flex flex-col justify-between">
          <div>
            <div className="px-4 py-3 border-b border-slate-800/80 flex items-center justify-between gap-2">
              <div className="text-sm font-semibold text-slate-100">
                Próximas órdenes de trabajo en curso ({upcomingOrders.length})
              </div>
              <button
                type="button"
                onClick={() => onGoToOrders()}
                className="text-xs text-sky-400 hover:text-sky-300 cursor-pointer whitespace-nowrap"
              >
                Gestionar órdenes
              </button>
            </div>
            <div className="divide-y divide-slate-800/60 text-xs">
              {ordersPagination.pagedItems.length === 0 ? (
                <div className="py-6 px-4 text-center text-slate-400">
                  No hay órdenes de trabajo programadas o en taller.
                </div>
              ) : (
                ordersPagination.pagedItems.map((wo) => {
                  const st = WORK_ORDER_STATUS_META[wo.status];
                  const pri = WORK_ORDER_PRIORITY_META[wo.priority];
                  return (
                    <div key={wo.id} className="px-4 py-3 flex items-center justify-between gap-3 hover:bg-slate-800/25">
                      <div className="min-w-0">
                        <div className="flex flex-wrap items-center gap-1.5">
                          <span className="font-mono font-semibold text-sky-300">{wo.id}</span>
                          <span className="font-semibold text-slate-100">{wo.unitCode}</span>
                          <span className={`font-semibold ${pri.colorClass}`}>· {pri.label}</span>
                          <span className={`font-medium ${st.colorClass}`}>· {st.label}</span>
                          {wo.autoGenerated && (
                            <span className="font-mono text-[10px] text-amber-300">· Auto</span>
                          )}
                        </div>
                        <div className="text-slate-300 truncate mt-0.5">{wo.title}</div>
                        <div className="text-slate-500 font-mono tabular-nums mt-0.5">
                          {formatServiceDate(wo.scheduledDate)} · {wo.workshopOrTech} · {money.fmt(wo.totalCost, wo.tenantId, { withCode: true })}
                        </div>
                      </div>
                      <button
                        type="button"
                        onClick={() => onGoToOrders(wo.id)}
                        className="px-2.5 py-1.5 rounded-lg bg-sky-600/20 hover:bg-sky-600/30 text-sky-300 border border-sky-500/30 cursor-pointer whitespace-nowrap shrink-0"
                      >
                        Ver orden
                      </button>
                    </div>
                  );
                })
              )}
            </div>
          </div>
          <Pagination
            page={ordersPagination.page}
            totalItems={ordersPagination.totalItems}
            pageSize={5}
            onPageChange={ordersPagination.setPage}
          />
        </div>
      </div>
    </div>
  );
}
